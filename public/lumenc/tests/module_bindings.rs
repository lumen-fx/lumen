// Installs every first-party module the dev build links, which only the
// `dev-run` build carries.
#![cfg(feature = "dev-run")]

//! The C++ and Python wrappers of the first-party modules are generated from
//! the functions each module registers, and checked in under the SDKs. This
//! test regenerates them and compares: a module whose functions changed, or a
//! new module, fails it until the wrappers are written again with
//!
//! ```text
//! UPDATE_BINDINGS=1 cargo test -p lumenc --features dev-run --test module_bindings
//! ```

// Every first-party module on the link line, so each leaves its install entry
// in the registry this test reads. `every_std_crate_is_anchored_here` keeps
// the list whole.
use lumen_archive as _;
use lumen_audio as _;
use lumen_browser as _;
use lumen_candela as _;
use lumen_candela_dev as _;
use lumen_canvas as _;
use lumen_cookie as _;
use lumen_download as _;
use lumen_fs as _;
use lumen_js as _;
use lumen_lua as _;
use lumen_process as _;
use lumen_rhai as _;
use lumen_storage as _;
use lumen_surface as _;
use lumen_svg as _;
use lumen_websocket as _;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use lumen_core::app::App;
use lumen_script::ScriptFnRegistry;
use lumenc::bindings::{cpp_header, python_module, wrapper_name};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the workspace root is readable")
}

/// What each wrapper file should hold, by path from the workspace root.
fn expected() -> BTreeMap<PathBuf, String> {
    let mut files = BTreeMap::new();
    let mut modules = lumen_module_registry::registered();
    modules.sort_by_key(|m| m.name);
    for module in modules {
        let mut app = App::new();
        assert_eq!(
            (module.install)(&mut app, ""),
            0,
            "{} installs with its defaults",
            module.name
        );
        let fns = app
            .world
            .get_resource::<ScriptFnRegistry>()
            .map(|r| r.fns().to_vec())
            .unwrap_or_default();
        if fns.is_empty() {
            continue;
        }
        let name = wrapper_name(module.name);
        files.insert(
            PathBuf::from(format!("public/lumenui/cpp/include/lumen_{name}.hpp")),
            cpp_header(module.name, &fns),
        );
        files.insert(
            PathBuf::from(format!("public/lumenui/python/lumen/{name}.py")),
            python_module(module.name, &fns),
        );
    }
    files
}

/// Wrapper files on disk: what the generators write, told apart from the
/// hand-written SDK files by the line each generated file opens with.
fn on_disk(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for dir in ["public/lumenui/cpp/include", "public/lumenui/python/lumen"] {
        for entry in std::fs::read_dir(root.join(dir)).expect("the SDK directory is readable") {
            let path = entry.expect("a readable entry").path();
            let text = std::fs::read_to_string(&path).unwrap_or_default();
            if text.starts_with("// Generated by `lumenc`")
                || text.starts_with("\"\"\"The `") && text.contains("Generated by ``lumenc``")
            {
                found.push(
                    path.strip_prefix(root)
                        .expect("under the root")
                        .to_path_buf(),
                );
            }
        }
    }
    found.sort();
    found
}

#[test]
fn module_wrappers_match_the_modules() {
    let root = root();
    let want = expected();
    assert!(
        want.keys().any(|p| p.ends_with("lumen_canvas.hpp")),
        "the canvas module is linked and has functions"
    );
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        for stale in on_disk(&root) {
            if !want.contains_key(&stale) {
                std::fs::remove_file(root.join(&stale)).expect("remove a stale wrapper");
            }
        }
        for (path, text) in &want {
            std::fs::write(root.join(path), text).expect("write a wrapper");
        }
        return;
    }
    let mut problems = Vec::new();
    for (path, text) in &want {
        match std::fs::read_to_string(root.join(path)) {
            Ok(have) if have == *text => {}
            Ok(_) => problems.push(format!("{} is out of date", path.display())),
            Err(_) => problems.push(format!("{} is missing", path.display())),
        }
    }
    for path in on_disk(&root) {
        if !want.contains_key(&path) {
            problems.push(format!("{} wraps no linked module", path.display()));
        }
    }
    assert!(
        problems.is_empty(),
        "{}; regenerate with UPDATE_BINDINGS=1",
        problems.join(", ")
    );
}

/// A crate added under `std/` is anchored above, or its wrappers would go
/// unchecked.
#[test]
fn every_std_crate_is_anchored_here() {
    let root = root();
    let source = std::fs::read_to_string(root.join("public/lumenc/tests/module_bindings.rs"))
        .expect("this test's source is readable");
    // Every module under `std/`, one level down or two (`std/candela/dev`),
    // by its package name: the crates that build on `lumen-module`.
    let dirs = |dir: &Path| -> Vec<PathBuf> {
        std::fs::read_dir(dir)
            .expect("the directory is readable")
            .map(|entry| entry.expect("a readable entry").path())
            .filter(|path| path.is_dir())
            .collect()
    };
    let mut missing = Vec::new();
    for path in dirs(&root.join("std"))
        .into_iter()
        .flat_map(|dir| std::iter::once(dir.clone()).chain(dirs(&dir)))
    {
        let Ok(text) = std::fs::read_to_string(path.join("Cargo.toml")) else {
            continue;
        };
        let manifest: toml::Table = toml::from_str(&text).expect("Cargo.toml parses");
        if manifest
            .get("dependencies")
            .and_then(|d| d.get("lumen-module"))
            .is_none()
        {
            continue;
        }
        let package = manifest["package"]["name"]
            .as_str()
            .expect("a package name");
        let anchor = format!("use {} as _;", package.replace('-', "_"));
        if !source.contains(&anchor) {
            missing.push(anchor);
        }
    }
    assert!(missing.is_empty(), "anchor these: {missing:?}");
}
